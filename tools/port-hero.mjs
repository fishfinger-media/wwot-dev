// Port the standalone hero (Desktop/wwot) into wwot-dev with namespaced classes and absolute asset URLs.
// Usage: node port.mjs <srcProject> <targetRepo>
import fs from 'node:fs';
import path from 'node:path';

const [SRC, DST] = process.argv.slice(2);
const P = 'wh-';
const BASE = 'https://wwot-dev.netlify.app/hero';
const keep = (c) => /^swiper/.test(c) || c.startsWith(P) || c.includes('${');
const pre = (c) => (keep(c) ? c : P + c);

const read = (f) => fs.readFileSync(f, 'utf8');
const write = (f, s) => { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, s); };

// ---------- helpers ----------
// split a class attribute value into tokens, keeping ${...} atomic
function splitClasses(v) {
  const out = []; let cur = ''; let depth = 0;
  for (let i = 0; i < v.length; i++) {
    const ch = v[i];
    if (ch === '$' && v[i + 1] === '{') { depth++; cur += '${'; i++; continue; }
    if (ch === '}' && depth) { depth--; cur += ch; continue; }
    if (/\s/.test(ch) && !depth) { if (cur) out.push(cur); cur = ''; continue; }
    cur += ch;
  }
  if (cur) out.push(cur);
  return out;
}
// prefix a token; a templated token like is-${i + 1} gets the prefix on its static head
const preTok = (t) => (t.includes('${') && !t.startsWith('${') ? P + t : pre(t));
const preClassAttr = (v) => splitClasses(v).map(preTok).join(' ');

// ---------- collect class set ----------
const html = read(path.join(SRC, 'index.html'));
const C = new Set();
for (const m of html.matchAll(/class="([^"]*)"/g)) splitClasses(m[1]).forEach((c) => C.add(c));

const STYLE_FILES = ['tokens.css', 'intro.css', 'hero.css', 'mobile-hero.css', 'popups.css', 'vector-motion.css'];
const stripComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '');
for (const f of STYLE_FILES) {
  const css = stripComments(read(path.join(SRC, 'src/styles', f)));
  for (const seg of css.split(/(?<=[{}])/)) {
    if (!seg.endsWith('{')) continue;
    for (const m of seg.matchAll(/\.(-?[a-zA-Z_][\w-]*)/g)) C.add(m[1]);
  }
}
const JS_FILES = fs.readdirSync(path.join(SRC, 'src')).filter((f) => f.endsWith('.js') && f !== 'nav.js' && f !== 'main.js');
for (const f of JS_FILES) {
  const js = read(path.join(SRC, 'src', f));
  for (const m of js.matchAll(/class="([^"]*)"/g)) splitClasses(m[1]).forEach((c) => C.add(c));
  for (const m of js.matchAll(/classList\.\w+\(([^)]*)\)/g)) for (const s of m[1].matchAll(/'([\w-]+)'/g)) C.add(s[1]);
}
for (const c of [...C]) if (keep(c)) C.delete(c);
const names = [...C].sort((a, b) => b.length - a.length).map((c) => c.replace(/[-]/g, '\\-'));
const selRe = new RegExp(`\\.(${names.join('|')})(?![\\w-])`, 'g');

// ---------- CSS ----------
function transformCss(css) {
  css = stripComments(css);
  return css.split(/(?<=[{}])/).map((seg) => (seg.endsWith('{') ? seg.replace(selRe, (_, c) => '.' + P + c) : seg)).join('');
}
const cssOut = [];
for (const f of STYLE_FILES) {
  let css = read(path.join(SRC, 'src/styles', f));
  if (f === 'tokens.css') {
    // Webflow already loads the fonts and owns body / element defaults; keep vars, utilities and scoped resets.
    css = css
      .replace(/@font-face\s*\{[^}]*\}/g, '')
      .replace(/\*, \*::before, \*::after \{ box-sizing: border-box; \}/, '.wh-root, .wh-root *, .wh-root *::before, .wh-root *::after { box-sizing: border-box; }')
      .replace(/html \{[^}]*\}/, '')
      .replace(/body \{[^}]*\}/, '')
      .replace(/img, video, svg \{([^}]*)\}/, '.wh-root img, .wh-root video, .wh-root svg {$1}')
      .replace(/^a \{([^}]*)\}/m, '.wh-root a {$1}')
      .replace(/\*, \*::before, \*::after \{ animation-duration/, '.wh-root *, .wh-root *::before, .wh-root *::after { animation-duration');
  }
  cssOut.push(`/* ${f} */\n` + transformCss(css));
}
write(path.join(DST, 'public/hero/hero.css'), '/* Generated by the hero port from the standalone rebuild. Linked from the Webflow Home page head. */\n' + cssOut.join('\n'));

// ---------- JS ----------
function transformJs(js, file) {
  // ?raw imports read straight from the public folder
  js = js.replace(/from '\/assets\//g, "from '../../public/hero/assets/");
  let usesBase = false;
  js = js.replace(/(['"`])\/assets\//g, (_, q) => { usesBase = true; return `HERO_BASE + ${q}/assets/`; });
  // classList args
  js = js.replace(/classList\.(\w+)\(([^)]*)\)/g, (m, fn, args) =>
    `classList.${fn}(` + args.replace(/'([\w-]+)'/g, (mm, c) => (C.has(c) ? `'${pre(c)}'` : mm)) + ')');
  // inside string literals: class="..." attributes and .class selectors
  js = js.replace(/'(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*"|`(?:[^`\\]|\\.)*`/g, (lit) => {
    let s = lit.replace(/class="([^"]*)"/g, (_, v) => `class="${preClassAttr(v)}"`);
    // leave ${...} expressions in template literals untouched (e.g. ${btn.dataset.button})
    s = s.split(/(\$\{[^}]*\})/).map((part) => (part.startsWith('${') ? part : part.replace(selRe, (_, c) => '.' + P + c))).join('');
    return s;
  });
  // the nav is the Webflow Navigation component (class .navigation), not the rebuild's #navigation
  js = js.replace(/'#navigation'/g, "'.navigation'");
  if (usesBase) js =`import { HERO_BASE } from './base.js';\n` + js;
  return js;
}
for (const f of JS_FILES) {
  let js = transformJs(read(path.join(SRC, 'src', f)), f);
  write(path.join(DST, 'src/hero', f), js);
}
write(path.join(DST, 'src/hero/base.js'),
  `// Where the hero's assets are served from (the Netlify build of this repo). Override with window.WWOT_HERO_BASE.\n` +
  `export const HERO_BASE = (typeof window !== 'undefined' && window.WWOT_HERO_BASE) || '${BASE}';\n`);

// ---------- Embed markup ----------
const pick = (start, end) => {
  const a = html.indexOf(start); const b = html.indexOf(end, a);
  if (a < 0 || b < 0) throw new Error('marker not found: ' + start);
  return html.slice(a, b);
};
let body = [
  pick('<svg class="sprite"', '<!-- ===================== NAV'),
  pick('<section class="section_home-hero', '<!-- ===================== MOBILE HERO'),
  pick('<section class="section_mobile-home', '<!-- Filler') ,
  pick('<!-- ===================== POPUPS', '<!-- ===================== INTRO'),
  pick('<!-- ===================== INTRO', '<script type="module"'),
].join('\n');
body = body
  .replace(/<!--[\s\S]*?-->/g, '')
  .replace(/class="([^"]*)"/g, (_, v) => `class="${preClassAttr(v)}"`)
  .replace(/(src|href|srcset|imagesrcset|poster|data-src)="([^"]*)"/g, (_, a, v) => `${a}="${v.replace(/(^|[\s,])\/assets\//g, `$1${BASE}/assets/`)}"`)
  .replace(/\n\s*\n+/g, '\n')
  .replace(/^\s+/gm, '');
const embed = `<div class="wh-root">\n${body}</div>`;
write(path.join(DST, 'src/hero/embed.html'), embed);

// head preloads for the Webflow page (first world's layers)
const head = [...html.matchAll(/<link rel="preload" as="image"[^>]*>/g)].map((m) => m[0].replace(/\/assets\//g, BASE + '/assets/')).join('\n');
write(path.join(DST, 'src/hero/head.html'), `<link rel="stylesheet" href="${BASE}/hero.css" />\n` + head + '\n');

console.log('classes prefixed:', C.size, ' embed chars:', embed.length);
